"""Build the method comparison table from raw result records only.

For every (experiment, method) the newest complete, non-smoke record in results/raw is used.
Writes results/processed/comparison__<timestamp>.csv and .md and prints the Markdown.

Usage: python scripts/make_table.py [EXPERIMENT ...]   (default: every experiment with results)
"""

from __future__ import annotations

import csv
import json
import sys
from datetime import datetime, timezone

from doge_exam.paths import load_paths

METHOD_ORDER = ("task-arithmetic", "ties", "doge-ta")


def latest_records(raw_dir):
    latest = {}
    for path in sorted(raw_dir.glob("*.json")):  # names end in a sortable UTC timestamp
        record = json.loads(path.read_text())
        if record.get("status") == "complete" and not record.get("fast_dev_run"):
            latest[record["run_id"]] = (path, record)
    return latest


def main() -> None:
    paths = load_paths()
    wanted = set(sys.argv[1:])
    latest = latest_records(paths.raw_results)
    references = {rid.split("__")[1]: rec for rid, (_, rec) in latest.items() if rid.startswith("ref__")}
    merges = [
        (path, rec)
        for path, rec in latest.values()
        if rec["kind"] == "merge" and (not wanted or rec["experiment"] in wanted)
    ]
    merges.sort(key=lambda pr: (pr[1]["experiment"], METHOD_ORDER.index(pr[1]["method"])))

    rows = []
    for experiment in dict.fromkeys(rec["experiment"] for _, rec in merges):
        tasks = next(rec["task_set"] for _, rec in merges if rec["experiment"] == experiment)
        for label, key in (("pretrained", "pretrained"), *((f"expert ({t})", f"expert-{t}") for t in tasks)):
            ref = references.get(key)
            if ref:
                acc = ref["per_task_accuracy"]
                rows.append({"experiment": experiment, "method": label, **{t: acc[t] for t in tasks},
                             "mean": sum(acc[t] for t in tasks) / len(tasks)})
        for path, rec in (pr for pr in merges if pr[1]["experiment"] == experiment):
            rows.append({
                "experiment": experiment,
                "method": rec["method"],
                **rec["per_task_accuracy"],
                "mean": rec["mean_accuracy"],
                "worst": rec["worst_task_accuracy"],
                "mean_norm_retention": rec["mean_normalized_retention"],
                "merge_s": rec["merge_time_seconds"],
                "peak_gpu_mb": rec["peak_memory_mb"],
                "source": path.name,
            })

    columns = list(dict.fromkeys(k for row in rows for k in row))
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    paths.processed_results.mkdir(parents=True, exist_ok=True)
    csv_path = paths.processed_results / f"comparison__{stamp}.csv"
    with csv_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=columns)
        writer.writeheader()
        writer.writerows(rows)

    def fmt(v):
        return "" if v is None else f"{v:.2f}" if isinstance(v, float) else str(v)

    lines = [
        "Accuracy in %, test split. Pretrained and expert rows are reference evaluations. "
        "Generated by scripts/make_table.py from results/raw.",
        "",
        "| " + " | ".join(columns) + " |",
        "|" + "---|" * len(columns),
    ]
    lines += ["| " + " | ".join(fmt(row.get(c)) for c in columns) + " |" for row in rows]
    md_path = csv_path.with_suffix(".md")
    md_path.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(csv_path, md_path, sep="\n")


if __name__ == "__main__":
    main()
